/**
 * Database schema. Every statement is CREATE TABLE IF NOT EXISTS, so it is
 * safe to run on every server start.
 */
const MASTERS = require('../utils/masters.config');

const T = 'ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci';
const STAMPS = `created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP`;

const masterTables = Object.values(MASTERS).map((m) => {
  const extra = Object.entries(m.extra || {})
    .map(([col, def]) => `  ${col} ${def},`)
    .join('\n');
  return `CREATE TABLE IF NOT EXISTS ${m.table} (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  description VARCHAR(500) NULL,
${extra}
  sort_order INT DEFAULT 0,
  status TINYINT(1) DEFAULT 1,
  ${STAMPS}
) ${T}`;
});

